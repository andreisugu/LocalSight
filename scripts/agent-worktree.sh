#!/usr/bin/env bash
# Create one isolated worktree for one agent.
#
#   bash scripts/agent-worktree.sh <slug>          # branch prep/<slug>
#   AGENT_PREP_ROOT=/path/to/prep bash scripts/agent-worktree.sh <slug>
#
# What it does, in order: fetch origin, refuse if the branch or directory already
# exists, create ../<repo>-prep/<slug> from the current origin/main, share the main
# checkout's frontend/node_modules through the existing link script, and write an
# ignored .agent/env with a free PW_PORT and PW_PAGES_PORT so two agents never fight
# over 4173/4317. Nothing is committed and nothing is pushed.
#
# The directory layout is deliberately <repo>-prep/<slug>, not inside the main
# checkout: `git status` in the main checkout stays clean and `git worktree list`
# stays the only registry of what exists.
set -euo pipefail

usage() {
  echo "usage: bash scripts/agent-worktree.sh <slug>" >&2
  echo "  slug: lowercase letters, digits and single dashes (creates branch prep/<slug>)" >&2
}

if [ "$#" -ne 1 ]; then
  usage
  exit 2
fi

SLUG="$1"
case "$SLUG" in
  --help|-h) usage; exit 0 ;;
esac
if ! [[ "$SLUG" =~ ^[a-z0-9]+(-[a-z0-9]+)*$ ]]; then
  echo "[agent-worktree] invalid slug: '$SLUG' (use kebab-case: my-change)" >&2
  exit 2
fi

if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  echo "[agent-worktree] not inside a git worktree" >&2
  exit 2
fi

WORKTREE="$(git rev-parse --show-toplevel)"
COMMON_DIR="$(git rev-parse --path-format=absolute --git-common-dir)"
MAIN="$(dirname "$COMMON_DIR")"
PREP_ROOT="${AGENT_PREP_ROOT:-$(dirname "$MAIN")/$(basename "$MAIN")-prep}"
TARGET="$PREP_ROOT/$SLUG"
BRANCH="prep/$SLUG"

echo "[agent-worktree] fetching origin"
if ! git -C "$WORKTREE" fetch --quiet origin; then
  echo "[agent-worktree] git fetch origin failed; not creating a worktree from a stale base" >&2
  exit 1
fi
BASE_SHA="$(git -C "$WORKTREE" rev-parse --short origin/main)"

if git -C "$WORKTREE" show-ref --verify --quiet "refs/heads/$BRANCH"; then
  echo "[agent-worktree] branch $BRANCH already exists; refusing to reuse it" >&2
  echo "                  run scripts/agent-status.sh to see its worktree, or pick another slug" >&2
  exit 1
fi
if git -C "$WORKTREE" show-ref --verify --quiet "refs/remotes/origin/$BRANCH"; then
  echo "[agent-worktree] remote branch origin/$BRANCH already exists; refusing to shadow it" >&2
  echo "                  check it out explicitly if that is really the work you want" >&2
  exit 1
fi
if [ -e "$TARGET" ]; then
  echo "[agent-worktree] $TARGET already exists; refusing to overwrite it" >&2
  exit 1
fi
if git -C "$WORKTREE" worktree list --porcelain | grep -Fxq "worktree $TARGET"; then
  echo "[agent-worktree] $TARGET is already registered as a worktree" >&2
  exit 1
fi

echo "[agent-worktree] $TARGET  branch $BRANCH  base origin/main@$BASE_SHA"
mkdir -p "$PREP_ROOT"
git -C "$WORKTREE" worktree add -b "$BRANCH" "$TARGET" origin/main

# Keep .agent/ out of `git status` without touching the tracked .gitignore. The
# exclude file is shared by every worktree of this repository.
EXCLUDE="$COMMON_DIR/info/exclude"
if [ -f "$EXCLUDE" ] && ! grep -qxF '.agent/' "$EXCLUDE"; then
  printf '\n# agent-worktree.sh: per-worktree agent env (untracked by design)\n.agent/\n' >> "$EXCLUDE"
fi

echo "[agent-worktree] linking frontend/node_modules"
if ! (cd "$TARGET" && bash frontend/scripts/link-node-modules.sh); then
  echo "[agent-worktree] WARNING: could not share node_modules (lockfile differs?)" >&2
  echo "                  run 'cd $TARGET/frontend && npm ci' once" >&2
fi

pick_port() {
  local port=""
  if command -v python3 >/dev/null 2>&1; then
    port="$(python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1]); s.close()' 2>/dev/null || true)"
  elif command -v node >/dev/null 2>&1; then
    port="$(node -e 'const net=require("net");const s=net.createServer();s.listen(0,"127.0.0.1",()=>{console.log(s.address().port);s.close()})' 2>/dev/null || true)"
  fi
  printf '%s' "$port"
}

PORT="$(pick_port)"
PAGES_PORT="$(pick_port)"
for _ in 1 2 3 4 5; do
  [ -n "$PORT" ] && [ "$PORT" != "$PAGES_PORT" ] && break
  PORT="$(pick_port)"
  PAGES_PORT="$(pick_port)"
done
if [ -z "$PORT" ] || [ "$PORT" = "$PAGES_PORT" ] || ! [[ "$PORT" =~ ^[0-9]+$ ]]; then
  echo "[agent-worktree] could not pick two free ports (need python3 or node)" >&2
  echo "                  set PW_PORT/PW_PAGES_PORT by hand in $TARGET/.agent/env" >&2
  PORT=0
  PAGES_PORT=0
fi

mkdir -p "$TARGET/.agent"
cat > "$TARGET/.agent/env" <<EOF
# Generated by scripts/agent-worktree.sh - untracked (excluded via .git/info/exclude).
# Source it before browser suites:  source .agent/env
export PW_PORT=$PORT
export PW_PAGES_PORT=$PAGES_PORT
export PW_BASE_URL=
EOF

cat <<EOF

[agent-worktree] ready
  worktree   $TARGET
  branch     $BRANCH (base origin/main@$BASE_SHA)
  ports      PW_PORT=$PORT  PW_PAGES_PORT=$PAGES_PORT
  env        $TARGET/.agent/env (ignored, not committed)

Next:
  cd $TARGET
  source .agent/env
  bash scripts/agent-preflight.sh        # confirm clean + base
  (cd frontend && npm run verify:fast)   # ~12 s: unit + build
  (cd frontend && npm run verify)        # ~21 s warm: full local gate
  # repeated e2e without rebuilding:
  (cd frontend && npm run e2e:serve)     # prints http://127.0.0.1:<port>/LocalSight/
  (cd frontend && PW_BASE_URL=<url> npm run e2e:pages)

Do not run 'npm ci' here: node_modules is a symlink into $MAIN.
EOF
